package jreact.compiler;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

/**
 * jsxjc — command-line entry point.
 *
 * <pre>java jreact.compiler.JsxjCompiler &lt;outDir&gt; &lt;srcDir&gt; [&lt;srcDir&gt;...]</pre>
 *
 * Pass 1 indexes component Props in every .jsxj and .java file; pass 2 writes each
 * .jsxj file as a .java file under outDir, keeping its package-relative path.
 */
public final class JsxjCompiler {

    private record Source(Path root, Path file) {}

    public static void main(String[] args) throws IOException {
        if (args.length < 2) {
            System.err.println("usage: jsxjc <outDir> <srcDir> [<srcDir>...]");
            System.exit(2);
        }
        Path outDir = Path.of(args[0]);
        PropsIndex index = new PropsIndex();
        List<Source> jsxj = new ArrayList<>();

        for (int i = 1; i < args.length; i++) {
            Path root = Path.of(args[i]);
            try (Stream<Path> walk = Files.walk(root)) {
                for (Path p : walk.filter(Files::isRegularFile).sorted().toList()) {
                    String name = p.getFileName().toString();
                    if (name.endsWith(".jsxj") || name.endsWith(".java")) index.scan(Files.readString(p));
                    if (name.endsWith(".jsxj")) jsxj.add(new Source(root, p));
                }
            }
        }

        int errors = 0;
        for (Source s : jsxj) {
            Path rel = s.root().relativize(s.file());
            try {
                String java = new JsxTranspiler(rel.toString(), Files.readString(s.file()), index).transpile();
                String outName = rel.getFileName().toString().replaceAll("\\.jsxj$", ".java");
                Path target = outDir.resolve(rel).resolveSibling(outName);
                Files.createDirectories(target.getParent());
                // Header goes on line 1 without a newline so .java line N == .jsxj line N.
                Files.writeString(target, "/* Generated by jsxjc from " + rel.toString().replace('\\', '/')
                        + " - do not edit. */ " + java, StandardCharsets.UTF_8);
            } catch (CompileError e) {
                System.err.println(e.format());
                errors++;
            }
        }

        if (errors > 0) {
            System.err.println(errors + " error(s)");
            System.exit(1);
        }
        System.out.println("jsxjc: " + jsxj.size() + " file(s) -> " + outDir);
    }
}
