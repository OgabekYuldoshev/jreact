package jreact.compiler;

import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

/**
 * jrxc — command-line entry point.
 *
 * <pre>java jreact.compiler.JrxCompiler &lt;outDir&gt; &lt;srcDir&gt; [&lt;srcDir&gt;...]</pre>
 *
 * Pass 1 indexes component Props in every .jrx and .java file; pass 2 writes each
 * .jrx file as a .java file under outDir, keeping its package-relative path.
 */
public final class JrxCompiler {

    private record Source(Path root, Path file) {}

    /** Outcome of {@link #compile}: how many .jrx files were seen and how many of them failed. */
    public record Result(int files, int errors) {}

    public static void main(String[] args) throws IOException {
        if (args.length < 2) {
            System.err.println("usage: jrxc <outDir> <srcDir> [<srcDir>...]");
            System.exit(2);
        }
        List<Path> dirs = new ArrayList<>();
        for (int i = 1; i < args.length; i++) dirs.add(Path.of(args[i]));
        Result r = compile(Path.of(args[0]), dirs, List.of(), System.err);
        if (r.errors() > 0) {
            System.err.println(r.errors() + " error(s)");
            System.exit(1);
        }
        System.out.println("jrxc: " + r.files() + " file(s) -> " + args[0]);
    }

    /**
     * Compiles every .jrx under {@code srcDirs} into {@code outDir}. All {@code srcDirs} (.jrx and .java) and
     * {@code extraIndexSources} (Java source text, e.g. the sources of jreact-core) are scanned for component
     * Props first. Compile errors go to {@code err}, one per file; the other files are still compiled.
     */
    public static Result compile(Path outDir, List<Path> srcDirs, List<String> extraIndexSources, PrintStream err)
            throws IOException {
        PropsIndex index = new PropsIndex();
        for (String src : extraIndexSources) index.scan(src);
        List<Source> jrx = new ArrayList<>();

        for (Path root : srcDirs) {
            if (!Files.isDirectory(root)) {      // e.g. a project that has no plain .java sources yet
                err.println("jrxc: skipping missing source folder " + root);
                continue;
            }
            try (Stream<Path> walk = Files.walk(root)) {
                for (Path p : walk.filter(Files::isRegularFile).sorted().toList()) {
                    String name = p.getFileName().toString();
                    if (name.endsWith(".jrx") || name.endsWith(".java")) index.scan(Files.readString(p));
                    if (name.endsWith(".jrx")) jrx.add(new Source(root, p));
                }
            }
        }

        int errors = 0;
        for (Source s : jrx) {
            Path rel = s.root().relativize(s.file());
            try {
                String java = new JsxTranspiler(rel.toString(), Files.readString(s.file()), index).transpile();
                String outName = rel.getFileName().toString().replaceAll("\\.jrx$", ".java");
                Path target = outDir.resolve(rel).resolveSibling(outName);
                Files.createDirectories(target.getParent());
                // Header goes on line 1 without a newline so .java line N == .jrx line N.
                Files.writeString(target, "/* Generated by jrxc from " + rel.toString().replace('\\', '/')
                        + " - do not edit. */ " + java, StandardCharsets.UTF_8);
            } catch (CompileError e) {
                err.println(e.format());
                errors++;
            }
        }
        return new Result(jrx.size(), errors);
    }
}
